function report = measure_supplied_reference_image()
% The user's seven-target image: red = sensor trace. Not a matched run.
root=fileparts(mfilename('fullpath'));
imagePath=fullfile(root,'docs','assets','original_seven_target_trajectories.png');
calibration=struct('imageSize',[1142 448], ...
    'xTicks',[44 -6000;1100 0],'yTicks',[24 2000;375 0], ...
    'region',[45 25 1099 374],'excludeRects',[982 33 1093 106], ...
    'color','red','pixelUncertainty',2, ...
    'source','User supplied seven-target field screenshot; axis endpoints read manually. Input-run pairing unconfirmed.');
report=digitize_reference_image(imagePath,calibration, ...
    fullfile(root,'outputs','supplied_image_measurement'));
end
