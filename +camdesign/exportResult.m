function paths = exportResult(project,result,outdir)
% Export explicitly identified candidate geometry and its complete settings.
camdesign.validateProject(project);
assert(result.metrics.geometryChecked,'cam:Unchecked','导出前需要完整几何检查。');
% Recompute to prevent stale UI/caller results being paired with changed inputs.
result=camdesign.evaluate(project,true);
if ~isfolder(outdir), mkdir(outdir); end
c=result.cam; r=result.route;
paths=struct('actual',fullfile(outdir,'cam_actual_candidate.csv'), ...
    'pitch',fullfile(outdir,'cam_pitch.csv'),'xyz',fullfile(outdir,'cam_actual_xyz_mm.txt'), ...
    'route',fullfile(outdir,'route.csv'),'hits',fullfile(outdir,'checkpoints.csv'), ...
    'project',fullfile(outdir,'project.mat'),'report',fullfile(outdir,'report.json'));
writetable(table(c.phi, c.actual(:,1),c.actual(:,2), ...
    'VariableNames',{'phase_rad','x_mm','y_mm'}),paths.actual);
writetable(table(c.phi,c.radius,c.pitch(:,1),c.pitch(:,2),rad2deg(c.pressure), ...
    'VariableNames',{'phase_rad','roller_center_radius_mm','x_mm','y_mm','pressure_deg'}),paths.pitch);
writematrix([c.actual,zeros(size(c.actual,1),1)],paths.xyz,'Delimiter','tab');
writetable(table(r.frontDistance,r.driveDistance,r.front(:,1),r.front(:,2), ...
    r.sensor(:,1),r.sensor(:,2),rad2deg(r.steering), ...
    'VariableNames',{'front_distance_mm','drive_distance_mm','front_x_mm','front_y_mm','sensor_x_mm','sensor_y_mm','steering_deg'}),paths.route);
writetable(table((1:size(project.targets,1))',project.targets(:,1),project.targets(:,2),result.hits.errors, ...
    'VariableNames',{'index','target_x_mm','target_y_mm','ordered_error_mm'}),paths.hits);
camdesign.saveProject(project,paths.project);
report=struct('schema','cam-replica-result-1','status','candidate_geometry_not_manufacturing_release', ...
    'units','mm/rad (CSV columns explicitly label deg where used)', ...
    'mechanism',project.params.mechanism,'params',project.params,'metrics',result.metrics, ...
    'effectiveGearRatio',c.effectiveRatio,'requestedGearRatio',c.requestedRatio, ...
    'ratioPolicy',c.ratioPolicy, ...
    'warnings',{result.warnings},'workEndDeg',rad2deg(c.workEnd), ...
    'validationScope','Discrete geometry and ideal no-slip kinematics only. No original-app or physical validation.', ...
    'phaseConvention','Positive profile phase; physical cam rotates clockwise with fixed follower at +X.');
fid=fopen(paths.report,'w','n','UTF-8'); assert(fid>=0,'cam:File','无法写入报告。');
cleaner=onCleanup(@()fclose(fid)); fprintf(fid,'%s',jsonencode(report,'PrettyPrint',true));
end
