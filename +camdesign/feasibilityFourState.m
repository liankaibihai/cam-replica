function state=feasibilityFourState(project,result)
% Independent dimensionless ranking; never substitutes for exact hard gates.
p=project.params; m=result.metrics; full=isequal(m.geometryChecked,true);
[~,trajectory]=camdesign.trajectoryBounds(result.route,p.bounds); control=camdesign.controlBounds(project);
if full, audit=result.visitOrder;
else, audit=camdesign.visitOrderAudit(result.route.sensor,project.targets,p.hitTolerance); end
order=audit.matchesRequiredOrderAndVisitCount;
orderViolation=editDistance(audit.expectedLocationIDs,audit.observedLocationIDs)/max(1,numel(audit.expectedLocationIDs));
if ~order, orderViolation=max(orderViolation,1/max(1,numel(audit.expectedLocationIDs))); end
cross=0; if full && m.intersectionCount>0, cross=m.intersectionCount/(1+m.intersectionCount); end
under=max(0,-m.minUndercutMargin); if m.minUndercutMargin==0, under=eps; end
workLimit=2*pi-deg2rad(p.returnAngleDeg);
returnViolation=max(0,result.cam.workEnd/workLimit-1);
if ~m.returnAngleSatisfied, returnViolation=max(eps,returnViolation); end
violations=[max(0,m.maxHitError/p.hitTolerance-1),max(0,m.maxPressureDeg/p.maxPressureDeg-1), ...
    max(0,m.maxSteeringDeg/p.maxSteeringDeg-1),under,returnViolation,trajectory.maxScaledViolation, ...
    double(control.enforced)*control.maxScaledViolation,orderViolation,cross];
numericFeasible=m.maxHitError<=p.hitTolerance && m.maxPressureDeg<=p.maxPressureDeg && m.maxSteeringDeg<=p.maxSteeringDeg ...
    && m.minUndercutMargin>0 && m.returnAngleSatisfied && trajectory.satisfied && control.gatePassed;
% Explicit independent small-error/pressure-margin preference. These are not
% softened/changed physical acceptance thresholds or changes to p.weights.
direct=max(1,sum(vecnorm(diff(project.targets),2,2)));
pressure=camdesign.pressurePreferenceProbe(result.cam,p);
parts=[m.routeLength/direct,(m.rmsHitError/p.hitTolerance)^2+(m.maxHitError/p.hitTolerance)^2, ...
    (pressure.maxPressureDeg/p.maxPressureDeg)^2, ...
    max(0,(pressure.maxPressureDeg-pressure.preferredMaximumDeg)/pressure.preferredMarginDeg)^2];
quality=parts*[1;.2;.03;.02];
state=struct('valid',all(isfinite([violations,quality,m.score])),'fullChecked',full, ...
    'numericFeasible',numericFeasible,'orderSatisfied',order, ...
    'feasible',full && numericFeasible && order && isfinite(m.intersectionCount) && m.intersectionCount==0, ...
    'violations',violations,'partialViolationSquared',sum(violations(1:8).^2), ...
    'violationSquared',sum(violations.^2),'maxNormalizedViolation',max(violations), ...
    'qualityObjective',quality,'qualityParts',parts,'qualityWeights',[1 .2 .03 .02], ...
    'pressurePreference',pressure, ...
    'metrics',m,'trajectory',trajectory,'controlBounds',control,'visitOrder',audit, ...
    'rankingVersion','feasibility-four-ranking-v2-small-error-margin', ...
    'violationNames',{{'hit','wholeCyclePressure','steering','undercut','fixedRatioReturn','fiveCenterBounds','enabledControlBounds','orderedEvents','selfIntersections'}}, ...
    'scope','Exact user gates determine training feasibility; ranking tolerances do not relax gates. Fast probes omit unknown self-intersections; every accepted candidate is fully checked. No body/UID/RFID or dense-grid acceptance implied.');
end
function distance=editDistance(a,b)
a=a(:); b=b(:); previous=0:numel(b);
for i=1:numel(a)
    current=[i zeros(1,numel(b))];
    for j=1:numel(b), current(j+1)=min([current(j)+1,previous(j+1)+1,previous(j)+(a(i)~=b(j))]); end
    previous=current;
end
distance=previous(end);
end
