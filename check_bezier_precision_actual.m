function report=check_bezier_precision_actual()
% Isolate actual-polygon discretization: fixed route and RK4 phase grids.
assert(batchStartupOptionUsed,'cam:PrecisionBatchOnly','Use an independent batch.');
root=fileparts(mfilename('fullpath')); folder=fullfile(root,'outputs','bezier_precision_20261031','actual_density');
assert(~isfile(fullfile(folder,'verification.json')),'cam:PrecisionEvidenceExists','Preserve previous evidence.');
if ~isfolder(folder), mkdir(folder); end
saved=load(fullfile(root,'outputs','model_mapping_20261031','quality_bezier','result.mat'),'q');
project=saved.q; project.params.samples=9601; project.params.camSamples=5761;
original=project; route=camdesign.route(project.nodes,project.params);
counts=[5761 11521 20001]; rows=struct([]); reports=cell(size(counts));
for k=1:numel(counts)
    camP=project.params; camP.camSamples=counts(k);
    cam=camdesign.camProfile(route,camP); frozen=cam.actual;
    [closure,simulation]=camdesign.verifyActualClosure(project,struct('cam',cam),Samples=2401);
    assert(closure.valid && closure.contactValid && closure.integrationConverged && closure.closurePassed);
    assert(isequal(cam.actual,frozen) && isequal(project,original) && isequal(closure.integrationSamples,[2401 4801]));
    row=struct('outlineSamples',counts(k),'referenceRouteSamples',9601, ...
        'inverseIntegrationSamples',closure.integrationSamples,'phaseEnd',cam.workEnd, ...
        'maxSensorDeviationMM',closure.maxSensorDeviationMM,'rmsSensorDeviationMM',closure.rmsSensorDeviationMM, ...
        'maxFrontDeviationMM',closure.maxFrontDeviationMM,'maxSteeringDeviationDeg',closure.maxSteeringDeviationDeg, ...
        'integrationMaxSensorDifferenceMM',closure.integrationMaxSensorDifferenceMM, ...
        'maxContactResidualMM',closure.maxContactResidualMM,'maxPenetrationMM',closure.maxPenetrationMM, ...
        'sampledActualMaxPressureDeg',closure.maxPressureDeg,'actualReturnDeg',closure.actualReturnDeg, ...
        'pressureSatisfied',closure.pressureSatisfied,'returnAngleSatisfied',closure.returnAngleSatisfied, ...
        'contactValid',closure.contactValid,'closurePassed',closure.closurePassed, ...
        'numericalMethod',cam.numericalMethod,'geometryFeasible',closure.geometryFeasible);
    if k==1, rows=row; else, rows(k)=row; end
    reports{k}=rmfield(closure,{'contact','fullCycleContact','hits','visitOrder','trajectoryBounds'});
    fprintf('BEZIER_ACTUAL_DENSITY outline=%d fixed route=9601 integration=[2401 4801] sensor max/RMS=%.12g/%.12g mm integration=%.12g mm\n', ...
        counts(k),row.maxSensorDeviationMM,row.rmsSensorDeviationMM,row.integrationMaxSensorDifferenceMM);
end
assert(all(diff([rows.maxSensorDeviationMM])<0) && rows(end).maxSensorDeviationMM<rows(1).maxSensorDeviationMM/5);
report=struct('release',version('-release'),'source','quality_bezier saved fixed35 flat curve', ...
    'routeAndPhysicalParametersUnchanged',true,'driveRatio',35,'trainingRuns',0, ...
    'grids',rows,'details',{reports}, ...
    'scope','Independent outline-density study: same saved curve, same 9601-point design reference and same 2401/4801 integration phases; each actual polygon is separately frozen during integration. Numerical and sampled rigid-contact model only, not a continuous or physical accuracy certificate.');
save(fullfile(folder,'results.mat'),'report','route');
fid=fopen(fullfile(folder,'verification.json'),'w','n','UTF-8'); assert(fid>=0);
closer=onCleanup(@()fclose(fid)); fprintf(fid,'%s\n',jsonencode(report,PrettyPrint=true));
fprintf('BEZIER_ACTUAL_DENSITY_PASS %.12g -> %.12g mm; physical gates remain separate\n',rows(1).maxSensorDeviationMM,rows(end).maxSensorDeviationMM);
end
